USE bloco_notas;
CREATE TABLE IF NOT EXISTS NOTA_DISFARCE (
 id_nota INT UNSIGNED NOT NULL AUTO_INCREMENT, id_usuario INT UNSIGNED NOT NULL, titulo VARCHAR(150) NOT NULL, conteudo TEXT NULL,
 data_criacao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, data_atualizacao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY (id_nota), KEY idx_nota_usuario_data (id_usuario, data_atualizacao),
 CONSTRAINT fk_nota_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;