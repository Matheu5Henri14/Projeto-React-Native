USE bloco_notas;
CREATE TABLE IF NOT EXISTS CONTATO_APOIO (
 id_contato INT UNSIGNED NOT NULL AUTO_INCREMENT, id_usuario INT UNSIGNED NOT NULL, nome_contato VARCHAR(120) NOT NULL,
 telefone_contato VARCHAR(20) NOT NULL, relacao VARCHAR(60) NULL, receber_alertas BOOLEAN NOT NULL DEFAULT TRUE, prioridade TINYINT UNSIGNED NOT NULL DEFAULT 1,
 data_criacao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, data_atualizacao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY (id_contato), KEY idx_contato_usuario (id_usuario, prioridade, nome_contato),
 CONSTRAINT chk_contato_prioridade CHECK (prioridade BETWEEN 1 AND 5),
 CONSTRAINT fk_contato_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;