USE bloco_notas;
CREATE TABLE IF NOT EXISTS REGISTRO_SIGILOSO (
 id_registro INT UNSIGNED NOT NULL AUTO_INCREMENT, id_usuario INT UNSIGNED NOT NULL, descricao TEXT NOT NULL, tipo VARCHAR(60) NULL,
 data_registro DATETIME NOT NULL, data_criacao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 data_atualizacao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY (id_registro), KEY idx_registro_usuario_data (id_usuario, data_registro),
 CONSTRAINT fk_registro_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;